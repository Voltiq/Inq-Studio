/** Advance widths in points, measured in the browser when it can (close enough for the overlay). */
function advances(text: string, em: number): number[] {
  let ctx: CanvasRenderingContext2D | null = null;
  try {
    ctx = typeof document === "undefined" ? null : document.createElement("canvas").getContext("2d");
  } catch {
    ctx = null;
  }
  if (ctx) ctx.font = `${em}px Helvetica, Arial, sans-serif`;
  const out = [0];
  for (let i = 1; i <= text.length; i++) out.push(ctx?.measureText ? ctx.measureText(text.slice(0, i)).width : i * em * 0.52);
  return out;
}

/** The lines the engine would find on a page of the sample, each its own block, so the edit tool has something to select and drag. */
function samplePageText(page: number): PageText {
  const lines: TextLine[] = (SAMPLE[page] ?? []).map((text, id) => {
    const em = id === 0 ? 20 : 11;
    const y = id === 0 ? 760 : 720 - (id - 1) * 18;
    const chars = advances(text, em);
    const w = chars[chars.length - 1];
    const style = { fontKey: font.key, fontName: "Helvetica", family: "Helvetica", bold: false, italic: false, size: em, em, color: [0, 0, 0] as [number, number, number] };
    return {
      id,
      src: "page",
      ops: [],
      text,
      spans: [{ start: 0, end: text.length, ...style }],
      ...style,
      quad: [[72, y - 0.21 * em], [72 + w, y - 0.21 * em], [72 + w, y + 0.72 * em], [72, y + 0.72 * em]],
      origin: [72, y],
      angle: 0,
      invisible: false,
      editable: true,
      note: null,
      chars,
      block: id,
    };
  });
  const blocks: Block[] = lines.map((l) => ({ id: l.id, lines: [l.id], text: l.text, align: "left", width: l.chars[l.chars.length - 1], leading: l.em * 1.2, quad: l.quad }));
  return { revision: 1, lines, blocks, rotation: 0 };
}


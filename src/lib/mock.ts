/** Installs the stand-in. Returns the commands that were asked for, in order (for tests). */
export function installMock(): string[] {
  const calls: string[] = [];
  mockWindows("main");
  mockIPC(
    (cmd, payload) => {
      calls.push(cmd);
      // Window, dialog and plugin calls: nothing happens, nothing is picked.
      if (cmd.startsWith("plugin:")) {
        if (cmd === "plugin:app|version") return "1.0.0";
        if (cmd === "plugin:updater|check") {
          if (typeof location === "undefined" || !location.search.includes("update")) return null;
          return { rid: 1, currentVersion: "1.0.0", version: "9.9.9", body: "### Added\n- **Something new**: what it does, in a sentence.\n\n### Fixed\n- A thing that went wrong before." };
        }
        return null;
      }
      if (cmd in answers) {
        const a = answers[cmd];
        return typeof a === "function" ? (a as (args: Record<string, unknown>) => unknown)((payload ?? {}) as Record<string, unknown>) : a;
      }
      throw READ_ONLY;
    },
    { shouldMockEvents: true },
  );
  return calls;
}

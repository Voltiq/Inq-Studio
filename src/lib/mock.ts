/** A two-page PDF with a few lines of Helvetica, written by hand. */
export function samplePdf(): Uint8Array {
  const page = (lines: string[]) =>
    `BT /F1 20 Tf 72 760 Td (${lines[0]}) Tj ET\n` +
    lines
      .slice(1)
      .map((l, i) => `BT /F1 11 Tf 72 ${720 - i * 18} Td (${l}) Tj ET`)
      .join("\n") +
    "\n0.12 0.32 0.78 rg 72 400 180 90 re f\n";
  const contents = [
    page(["Inq Studio sample", "This document is generated by the browser preview.", "It has two pages, a few lines of text and a blue rectangle.", "Editing needs the desktop app: here every change is refused."]),
    page(["Second page", "Nothing much to see here."]),
  ];
  const objects: string[] = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Count 2 /Kids [3 0 R 5 0 R] >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 7 0 R >> >> >>",
    `<< /Length ${contents[0].length} >>\nstream\n${contents[0]}\nendstream`,
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 6 0 R /Resources << /Font << /F1 7 0 R >> >> >>",
    `<< /Length ${contents[1].length} >>\nstream\n${contents[1]}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
  ];
  let out = "%PDF-1.7\n";
  const offsets: number[] = [];
  objects.forEach((o, i) => {
    offsets.push(out.length);
    out += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const xref = out.length;
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const o of offsets) out += `${String(o).padStart(10, "0")} 00000 n \n`;
  out += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return new TextEncoder().encode(out);
}

